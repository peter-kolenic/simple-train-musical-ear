// The first browser language that the app has, else the fallback.
// preferred: a list of language tags, for example navigator.languages.
export const pickLanguage = (preferred) => {
  const tags = Array.isArray(preferred) ? preferred : [];
  const found = tags
    .map((tag) => String(tag).toLowerCase().split('-')[0])
    .find((base) => LANGUAGES.includes(base));
  return found || FALLBACK_LANGUAGE;
};

// The parameter names in a message, in order.
export const messageParams = (text) => (text.match(/\{\w+\}/g) || []).map((p) => p.slice(1, -1));

// The message in lang, else in the fallback language, else the key itself.
// A parameter that params does not give stays as "{name}".
export const translate = (lang, key, params = {}) => {
  const table = MESSAGES[lang] || {};
  const text = table[key] ?? MESSAGES[FALLBACK_LANGUAGE][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole));
};
